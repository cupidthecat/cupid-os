/**
 * @file guest_job.h
 * @brief Declare the shared file and memory adapter for guest toolchain workers.
 */

#ifndef CUPID_BOOTSTRAP_GUEST_JOB_H
#define CUPID_BOOTSTRAP_GUEST_JOB_H

#include "ctool.h"
#include "cupid.h"

#define CUPID_GUEST_CACHE_SLOTS 64u
#define CUPID_GUEST_PATH_BYTES(count) ((count) * VFS_MAX_PATH + 1u)
#define CUPID_GUEST_PATH_JOB_BYTES CUPID_GUEST_PATH_BYTES(2u)
#define CUPID_GUEST_OBJECT_LIST_LIMIT 256u
#define CUPID_GUEST_OBJECT_LIST_BYTES CUPID_GUEST_PATH_BYTES(2u * CUPID_GUEST_OBJECT_LIST_LIMIT)

typedef struct {
    const char *path;
    ctool_string_t text; /* If present, the request is generated by CupidBuild. */
    const char *project_directory; /* Set for requests from a local project plan. */
} cupid_guest_request_t;

typedef struct {
    void *allocation;
    ctool_u32 size;
} cupid_guest_cached_allocation_t;

typedef struct {
    cupid_syscall_table_t *sys;
    ctool_string_t input_prefix;
    const char *pending_path;
    ctool_u32 output_extent; /* Optional zero-filled extent for a fresh HomeFS file. */
    /* Finish a private candidate before HomeFS publishes it. */
    ctool_status_t (*prepare_output)(void *context, int fd);
    void *output_context;
    ctool_u32 cached_bytes;
    cupid_guest_cached_allocation_t cache[CUPID_GUEST_CACHE_SLOTS];
} cupid_guest_io_t;

/* The adapter and syscall table must outlive the job. Input paths are
 * relative to input_prefix. A pending path under /home also reserves the
 * matching name under /tmp for temporary products. */
ctool_job_config_t cupid_guest_job_config(cupid_guest_io_t *io);

/* Return the length of a writable directory prefix, including its slash. */
ctool_u32 cupid_guest_output_prefix(cupid_syscall_table_t *sys, ctool_string_t path);

/* Copy a request into a writable, NUL-terminated parser buffer. */
int cupid_guest_read_request(cupid_syscall_table_t *sys, const cupid_guest_request_t *job,
                             char *file, ctool_u32 capacity);

/* Read two canonical paths. The output is under /home or /tmp. Views borrow file. */
int cupid_guest_read_path_job(cupid_syscall_table_t *sys, const cupid_guest_request_t *job,
                              char *file, ctool_invocation_request_t *invocation);

/* Each field occupies one line. The last path is the writable output. */
int cupid_guest_read_paths(cupid_syscall_table_t *sys, const cupid_guest_request_t *job,
                          char *file, ctool_u32 capacity, ctool_path_t *paths, ctool_u32 count);
int cupid_guest_read_path_lines(cupid_syscall_table_t *sys, char **cursor, char *end,
                               ctool_path_t *paths, ctool_u32 count);
char *cupid_guest_next_job_line(char **cursor, char *end);
const char *cupid_guest_project_path(cupid_syscall_table_t *sys, const char *directory,
                                    const char *name, char absolute[VFS_MAX_PATH]);
int cupid_guest_read_root(cupid_syscall_table_t *sys, char **cursor, char *end,
                          const char *fallback, const char *project_directory,
                          char absolute[VFS_MAX_PATH], const char **root);

/* Read all source and object pairs before any output can be published. */
ctool_u32 cupid_guest_read_object_list(cupid_syscall_table_t *sys, char *cursor, char *end,
                                        const char *reserved_leaf, ctool_invocation_request_t *items);

/* Return cached, released blocks. Live allocations still belong to the job. */
void cupid_guest_job_drain_cache(cupid_guest_io_t *io);

#endif
